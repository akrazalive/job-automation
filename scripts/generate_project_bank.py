def build_records() -> list[dict]:
    records = []
    for stack_key, stack_label, category, default_tools, default_effort, projects in STACKS:
        for i, project in enumerate(projects, start=1):
            title, description, features = project[0], project[1], project[2]
            extra_tools = project[3] if len(project) > 3 and project[3] else []
            effort = project[4] if len(project) > 4 and project[4] else default_effort
            tools = list(dict.fromkeys([*default_tools, *extra_tools]))  # dedupe, keep order
            records.append({
                "id": f"{stack_key}-{i:02d}",
                "stack": stack_key,
                "stack_label": stack_label,
                "category": category,
                "tools": tools,
                "title": title,
                "description": description,
                "features": features,
                "estimated_effort": effort,
            })
    return records


def main() -> None:
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--force", action="store_true",
        help="Overwrite project_bank.json even if it contains entries this "
             "script didn't generate (e.g. added manually via the dashboard's "
             "'Add project' form). Without this flag, those get detected and "
             "the script refuses to clobber them.",
    )
    args = parser.parse_args()

    records = build_records()
    generated_ids = {r["id"] for r in records}

    if OUTPUT_PATH.exists() and not args.force:
        existing = json.loads(OUTPUT_PATH.read_text(encoding="utf-8"))
        custom_ids = {r["id"] for r in existing} - generated_ids
        if custom_ids:
            print(
                f"Refusing to overwrite: {OUTPUT_PATH} has {len(custom_ids)} "
                "entries not produced by this script (likely added manually "
                "via the dashboard). Re-run with --force to overwrite anyway "
                "(this WILL discard those entries), or add them into the "
                "STACKS list here instead so they're preserved.",
            )
            print(f"  Custom ids: {sorted(custom_ids)}")
            raise SystemExit(1)

    OUTPUT_PATH.write_text(json.dumps(records, indent=2), encoding="utf-8")
    print(f"Wrote {len(records)} project records to {OUTPUT_PATH}")
    by_stack: dict[str, int] = {}
    for r in records:
        by_stack[r["stack_label"]] = by_stack.get(r["stack_label"], 0) + 1
    for label, count in sorted(by_stack.items(), key=lambda x: -x[1]):
        print(f"  {label}: {count}")


if __name__ == "__main__":
    main()
